// Small shared building blocks: section wrapper, AI label, notices, warning banner.
import { useContext, useState, type ReactNode } from "react";
import type { DocumentWarning } from "../api/types";
import { WARNING_INFO, isNote, plural, type Tone } from "../lib/labels";
import { FeedbackScopeContext, sectionId } from "../lib/jobActions";
import { CitationChip } from "./Citations";
import { FeedbackButtons } from "./Feedback";
import { Icon, type IconName } from "./Icon";

/** Marks content produced by the local model (CLAUDE.md section 10). */
export function AiLabel() {
  return (
    <span
      className="ai-label"
      title="Produced by a local AI model. Verify it against the cited page before relying on it."
    >
      AI-generated
    </span>
  );
}

/**
 * One notice at the top of the results: everything below is AI-generated.
 * (Per-item badges are kept only on visual element cards, the most
 * interpretive output.)
 */
export function AiNotice() {
  return (
    <div className="ai-notice" role="note">
      <span className="ai-label" aria-hidden="true">
        AI
      </span>
      <span>
        All analysis below is AI-generated by a local model. Verify it against
        the cited pages.
      </span>
    </div>
  );
}

/** A titled section of results, with thumbs up/down feedback in its header. */
export function Section({
  title,
  count,
  children,
}: {
  title: string;
  count?: number;
  children: ReactNode;
}) {
  const scope = useContext(FeedbackScopeContext);
  return (
    <section className="section" aria-label={title}>
      <header className="section-head">
        <h3>
          {title}
          {count !== undefined && <span className="count">{count}</span>}
        </h3>
        <FeedbackButtons
          target="section"
          targetId={sectionId(scope, title)}
          label={title}
        />
      </header>
      {children}
    </section>
  );
}

const TONE_ICON: Record<Tone, IconName> = {
  neutral: "info",
  info: "info",
  success: "check",
  warning: "alert",
  danger: "cross",
};

/** A banner with an icon and text; colour is never the only signal. */
export function Notice({
  tone,
  title,
  children,
  icon,
  action,
  role,
}: {
  tone: Tone;
  title: string;
  children?: ReactNode;
  icon?: IconName;
  action?: ReactNode;
  role?: "alert" | "status";
}) {
  return (
    <div className={`notice tone-${tone}`} role={role}>
      <Icon name={icon ?? TONE_ICON[tone]} />
      <div className="notice-body">
        <p className="notice-title">{title}</p>
        {children && <div className="notice-text">{children}</div>}
      </div>
      {action}
    </div>
  );
}

/**
 * Collapsible list of a document's warnings and notes: security warnings first,
 * then other warnings, then info-level notes. With only notes, the banner itself
 * uses the info tone and says "note".
 */
export function WarningBanner({
  warnings,
  documentId,
}: {
  warnings: DocumentWarning[];
  documentId?: string;
}) {
  const [open, setOpen] = useState(true);
  if (!warnings.length) return null;
  const rank = (w: DocumentWarning) =>
    WARNING_INFO[w.code].security ? 0 : isNote(w.code) ? 2 : 1;
  const sorted = [...warnings].sort((a, b) => rank(a) - rank(b));
  const security = sorted.some((w) => WARNING_INFO[w.code].security);
  const notes = sorted.filter((w) => isNote(w.code)).length;
  const real = sorted.length - notes;
  const tone = security ? "danger" : real > 0 ? "warning" : "info";
  const label = [
    real > 0 ? plural(real, "warning") : null,
    notes > 0 ? plural(notes, "note") : null,
  ]
    .filter(Boolean)
    .join(", ");
  return (
    <div className={`warnings tone-${tone}`}>
      <button
        type="button"
        className="warnings-toggle"
        aria-expanded={open}
        onClick={() => setOpen(!open)}
      >
        <Icon name={security ? "shield" : tone === "info" ? "info" : "alert"} />
        <span>
          {label}
          {security ? ": includes a security warning" : ""}
        </span>
        <span className="warnings-hint">{open ? "Hide" : "Show"}</span>
      </button>
      {open && (
        <ul className="warnings-list">
          {sorted.map((w, i) => {
            const info = WARNING_INFO[w.code];
            return (
              <li key={i} className={`tone-${info.tone}`}>
                <Icon
                  name={
                    info.security
                      ? "shield"
                      : info.tone === "info"
                        ? "info"
                        : "alert"
                  }
                />
                <div>
                  <p className="warning-title">
                    {info.title}
                    {w.page !== null && documentId && (
                      <CitationChip
                        citation={{ document_id: documentId, page: w.page }}
                      />
                    )}
                  </p>
                  <p className="warning-text">{w.message}</p>
                </div>
              </li>
            );
          })}
        </ul>
      )}
    </div>
  );
}
