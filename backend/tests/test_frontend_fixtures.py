"""Real API responses, captured in mock mode, as fixtures for the frontend tests.

The frontend's TypeScript types (``frontend/src/api/types.ts``) are hand-written
to mirror the Pydantic schemas. These tests run real jobs through the API in
mock mode and keep the responses in ``frontend/src/test/fixtures/`` as typed
TypeScript modules::

    const fixture: JobResponse = { ...real API output... };

so ``tsc`` checks real API output against the hand-written types on every
frontend build (a missing or extra field, or an unknown enum value, is a
compile error), and the frontend tests render real API output, not hand-made
objects. JSON files would not do this: TypeScript widens string literals in
imported JSON, which forces a cast that hides mismatches.

Snapshot behaviour:

* If a fixture file is missing, or ``UPDATE_FRONTEND_FIXTURES=1`` is set, it is written.
* Otherwise the test fails when the API output differs from the committed file,
  so a schema change cannot silently leave the frontend fixtures (and types) behind.

Volatile values are normalised so the files are stable: UUIDs become fixed IDs
in order of first appearance, and timestamps become a fixed instant.
"""

import asyncio
import json
import os
import re
from pathlib import Path
from typing import Any

import httpx
import pytest

from app.config import Settings
from app.main import create_app
from tests import pdf_factory
from tests.conftest import app_client
from tests.ticket_factory import TICKETS, ticket_pdf

FIXTURE_DIR = Path(__file__).resolve().parents[2] / "frontend" / "src" / "test" / "fixtures"
UPDATE = os.environ.get("UPDATE_FRONTEND_FIXTURES") == "1"

_UUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")
FIXED_TIME = "2026-01-01T09:00:00Z"


def normalise(data: Any) -> Any:
    """Replace UUIDs (stable, in order of appearance) and timestamps."""
    text = json.dumps(data)
    mapping: dict[str, str] = {}
    for match in _UUID.findall(text):
        mapping.setdefault(match, f"00000000-0000-4000-8000-{len(mapping) + 1:012d}")
    for real, fixed in mapping.items():
        text = text.replace(real, fixed)
    result = json.loads(text)
    if isinstance(result, dict):
        for key in ("created_at", "updated_at"):
            if key in result:
                result[key] = FIXED_TIME
    return result


def check_fixture(name: str, type_name: str, data: Any) -> None:
    """Write the typed fixture module if missing or updating; otherwise compare with it.

    Args:
        name: File name, e.g. ``jobCompleted.ts``.
        type_name: TypeScript type from ``src/api/types.ts`` the data must satisfy.
        data: The API response body.
    """
    path = FIXTURE_DIR / name
    body = json.dumps(normalise(data), indent=2, ensure_ascii=False)
    rendered = (
        "// Generated by backend/tests/test_frontend_fixtures.py from a real mock-mode API\n"
        "// response. Do not edit by hand: regenerate with UPDATE_FRONTEND_FIXTURES=1.\n"
        f"import type {{ {type_name.removesuffix('[]')} }} from '../../api/types';\n\n"
        f"const fixture: {type_name} = {body};\n\n"
        "export default fixture;\n"
    )
    if UPDATE or not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(rendered, encoding="utf-8", newline="\n")
        return
    assert path.read_text(encoding="utf-8") == rendered, (
        f"{name} is out of date with the API. If the change is intended, regenerate with "
        "UPDATE_FRONTEND_FIXTURES=1 pytest tests/test_frontend_fixtures.py, then update "
        "frontend/src/api/types.ts to match."
    )


async def _run_job(
    client: httpx.AsyncClient, files: list[tuple[str, bytes]], profile: str = "general"
) -> dict[str, Any]:
    response = await client.post(
        "/api/jobs",
        files=[("files", (name, data, "application/pdf")) for name, data in files],
        data={"profile": profile},
    )
    assert response.status_code == 202, response.text
    job_id = response.json()["job_id"]
    for _ in range(600):
        job: dict[str, Any] = (await client.get(f"/api/jobs/{job_id}")).json()
        if job["status"] in {"completed", "partial", "failed"}:
            return job
        await asyncio.sleep(0.05)
    raise AssertionError("job did not finish")


@pytest.fixture
async def mock_client(settings: Settings) -> Any:
    async with app_client(create_app(settings)) as client:
        yield client


async def test_completed_job_fixture(mock_client: httpx.AsyncClient) -> None:
    job = await _run_job(
        mock_client,
        [
            ("report_a.pdf", pdf_factory.incident_report_pdf()),
            ("report_b.pdf", pdf_factory.witness_report_pdf()),
            ("suspicious_report.pdf", pdf_factory.prompt_injection_pdf()),
        ],
    )
    assert job["status"] == "completed"
    assert job["consolidated"] is not None
    check_fixture("jobCompleted.ts", "JobResponse", job)


async def test_incident_job_fixture(mock_client: httpx.AsyncClient) -> None:
    job = await _run_job(
        mock_client, [(f"{t.key}.pdf", ticket_pdf(t)) for t in TICKETS], profile="incident"
    )
    assert job["status"] == "completed"
    assert job["consolidated"]["rule_based"] is True
    check_fixture("jobIncident.ts", "JobResponse", job)


async def test_partial_job_fixture(mock_client: httpx.AsyncClient) -> None:
    job = await _run_job(
        mock_client,
        [
            ("report_a.pdf", pdf_factory.incident_report_pdf()),
            ("broken_analysis.pdf", pdf_factory.mock_fail_pdf()),
            ("not_a_pdf.pdf", pdf_factory.fake_pdf()),
        ],
    )
    assert job["status"] == "partial"
    assert [d["status"] for d in job["documents"]] == ["completed", "failed", "rejected"]
    check_fixture("jobPartial.ts", "JobResponse", job)


async def test_failed_job_fixture(mock_client: httpx.AsyncClient) -> None:
    job = await _run_job(mock_client, [("broken_analysis.pdf", pdf_factory.mock_fail_pdf())])
    assert job["status"] == "failed"
    check_fixture("jobFailed.ts", "JobResponse", job)


async def test_static_endpoint_fixtures(mock_client: httpx.AsyncClient) -> None:
    for name, type_name, path in [
        ("healthMock.ts", "HealthResponse", "/api/health"),
        ("config.ts", "ConfigResponse", "/api/config"),
        ("profiles.ts", "ProfileInfo[]", "/api/profiles"),
    ]:
        response = await mock_client.get(path)
        assert response.status_code == 200
        check_fixture(name, type_name, response.json())


async def test_upload_response_fixture(mock_client: httpx.AsyncClient) -> None:
    response = await mock_client.post(
        "/api/jobs",
        files=[
            ("files", ("report_a.pdf", pdf_factory.valid_text_pdf(), "application/pdf")),
            ("files", ("locked.pdf", pdf_factory.encrypted_pdf(), "application/pdf")),
        ],
    )
    assert response.status_code == 202
    check_fixture("jobCreated.ts", "JobCreatedResponse", response.json())
